function normalizeCountryKey(raw: string): string {
  return raw
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/['’]/g, '')
    .replace(/\s+/g, ' ')
}

export function countryToFlagIso(country?: string | null): string | null {
  if (!country) return null
  const key = normalizeCountryKey(country)
  if (/^[a-z]{2}$/.test(key)) return key === 'uk' ? 'gb' : key
  return COUNTRY_TO_ISO[key] || null
}

/** Last comma segment of "City, Country" (or airport full label). */
export function parseCountryFromFull(full?: string | null): string | null {
  if (!full) return null
  const parts = String(full)
    .split(',')
    .map((p) => p.trim())
    .filter(Boolean)
  if (parts.length < 2) return null
  return parts[parts.length - 1] || null
}

export function countryIsoFromIata(iata?: string | null): string | null {
  const code = (iata || '').trim().toUpperCase()
  if (!code) return null
  return IATA_TO_ISO[code] || null
}

/** Best-effort ISO for a flight leg / destination card. */
export function countryIsoForAirport(
  iata?: string | null,
  fullLabel?: string | null,
): string | null {
  const fromLabel = countryToFlagIso(parseCountryFromFull(fullLabel))
  if (fromLabel) return fromLabel
  return countryIsoFromIata(iata)
}
